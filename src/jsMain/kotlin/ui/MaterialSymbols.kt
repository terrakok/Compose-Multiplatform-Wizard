/** Material icon offered by the app icon editor, in both styles the editor supports. */
data class MaterialSymbol(
    val name: String,
    private val filled: SvgIconComponent,
    private val outlined: SvgIconComponent,
) {
    private val filledSvg by lazy { renderToStaticMarkup(filled.create()) }
    private val outlinedSvg by lazy { renderToStaticMarkup(outlined.create()) }

    fun component(style: AppIconSymbolStyle): SvgIconComponent = when (style) {
        AppIconSymbolStyle.Filled -> filled
        AppIconSymbolStyle.Outlined -> outlined
    }

    fun svgString(style: AppIconSymbolStyle): String = when (style) {
        AppIconSymbolStyle.Filled -> filledSvg
        AppIconSymbolStyle.Outlined -> outlinedSvg
    }
}

